"""ניתוח הודעות לפי כללים (שלב ראשון, לפני AI).

analyze(text) מחזיר מילון באותו מבנה שמנתח AI יחזיר בעתיד, כך שאפשר להחליף מנתח בלי לשנות
את שאר המערכת. הכללים שקופים ופשוטים; הם לא "מבינים" טקסט, ולכן כל אירוע מסומן
"נותח אוטומטית לפי כללים".
"""
import re

from .gazetteer import NORTH_REGIONS, PLACES, STREETLIKE, regions_for

VERSION = "rules-3"   # rules-2: כיסוי ארצי + שיוך לאזורים; rules-3: הבחנה בין דיווח למאמר/סיכום
HEB = "֐-׿"

TYPE_RULES = [  # הסדר קובע עדיפות כשיש כמה התאמות
    ("security", r"צבע אדום|ירי רקטות|רקטות|טילים|טיל |כטב\"ם|כלי טיס עוין|חדירת מחבלים|חשש לחדירת|מחבל|פיגוע|"
                 r"יירוט|יירוטים|נפילה|נפילות|אזעק|התרעה מפיקוד העורף|התרעות|שיגור|רסיסים|חפץ חשוד|אמל\"ח|"
                 r"מרחב (?:ה)?מוגן|למרחב המוגן|הוסר החשש|פיצוצים|שובלים|עדכון ביטחוני|הנחיות התגוננות"),
    ("fire", r"שריפ|שרפה|בוער|בוערת|עלה באש|עלתה באש|לוחמי אש|צוותי כיבוי|כבאות והצלה"),
    ("accident", r"תאונ|התנגש|התהפכ|פגע וברח|הולך רגל|הולכת רגל|נפגע מרכב|נפגעה מרכב|רוכב אופנוע|קורקינט|אופניים חשמליים"),
    ("closure", r"חסימ|נחסם|נחסמה|חסום|חסומה|נסגר לתנועה|נסגרה לתנועה|הסדרי תנועה|עומסי תנועה|פקק"),
    ("infrastructure", r"הפסקת חשמל|הפסקות חשמל|הפסקת מים|תקלה ב(?:חשמל|מים|תקשורת)|חברת החשמל|ביוב|פיצוץ צנרת|"
                       r"מי השתיה|מי השתייה|מי שתייה|הרתיחו|עבודות תשתית|עבודות ב(?:רחוב|כביש)"),
    ("weather", r"סערה|שיטפון|שיטפונות|הצפה|הצפות|שלג|ברד|רעידת אדמה|גשם כבד|אזהרת מזג"),
    ("hazard", r"חומ\"ס|חומרים מסוכנים|דליפ|זיהום|מפגע|נפילת עץ|קריסת"),
    ("medical", r"מד\"א|פצוע|פצועה|פצועים|נפגע|נפגעה|נפגעים|מחוסר הכרה|החייאה|נקבע מותו|נקבע מותה"),
]
SEVERE = re.compile(r"נהרג|נהרגה|הרוג|נקבע מות|אנוש|במצב קשה|פצוע קשה|פצועה קשה|פגיעה ישירה")
MEDIUM = re.compile(r"בינוני|לכודים|לכוד|נלכד|פצועים|נפגעים|חדירת מחבלים|ירי רקטות")
ENDED = re.compile(r"האירוע הסתיים|הסתיים|הוסר החשש|נפתח לתנועה|נפתחה לתנועה|כובתה|נשלטה|הושלט|יכולים לצאת")


def _pattern(name: str) -> re.Pattern:
    # תחיליות עבריות נפוצות: ב, ל, מ, ו, ה, ש, כ (עד שתיים), ולא חלק ממילה ארוכה יותר
    body = re.escape(name).replace("\\ ", r"[\s\-–]+")
    tail = rf"(?![{HEB}\w])" + (rf"(?!\s+[{HEB}])" if name in STREETLIKE else "")
    return re.compile(rf"(?<![{HEB}\w])(?:[ובלמהשכ]{{0,2}}){body}{tail}")


_INDEX = []
for kind, name, aliases, lat, lon in PLACES:
    for n in [name, *aliases]:
        _INDEX.append((kind, name, _pattern(n)))
KIND_RANK = {"junction": 0, "locality": 1, "road": 2, "region": 3}   # מהמדויק לכללי


def find_places(text: str) -> list[dict]:
    hits = {}
    for kind, name, pat in _INDEX:
        m = pat.search(text)
        if m and (name not in hits or m.start() < hits[name]["pos"]):
            hits[name] = {"name": name, "kind": kind, "pos": m.start()}
    return sorted(hits.values(), key=lambda h: (KIND_RANK[h["kind"]], h["pos"]))


# מקום שמוזכר רק כיעד פינוי לבית חולים אינו מקום האירוע ("פונה לבית החולים בנהריה")
HOSPITAL = re.compile(r"(?:ל|ב|ה|ו)?(?:בית ה?חולים|בי[\"״]ח|ביה[\"״]ח|מרכז ה?רפואי|מרכז ה?רפואה|"
                      r"מלר\"ד|המיון|חדר ה?מיון)[^.,;\n]{0,45}")


# שם רחוב שהוא גם שם של יישוב ("ברחוב משמר הירדן בתל אביב"): עד שתי מילים אחרי "רחוב", עד מילה שמתחילה ב-ב
STREET = re.compile(rf"(?:ב|ל|מ|ו)?(?:רחוב|רח'|רח׳|שדרות|שד'|שד׳)(?:\s+(?!ב)[{HEB}\"'׳״\-]+){{1,2}}")


# הודעה שעוסקת בזירה מחוץ לישראל. בה, אזכור כללי של "הצפון" אינו מקום האירוע.
ABROAD = re.compile(r"לבנון|לבנוני|בלבנון|חיזבאללה|הכפר השיעי|בכפר השיעי|סוריה|בסוריה|סורי|"
                    r"רצועת עזה|ברצועה|בעזה|דיווחים ערביים|כלי תקשורת בלבנון")
GENERIC = {name for kind, name, *_ in PLACES if kind == "region"}


# ---------- סוגה: האם זו ידיעה על אירוע שקורה עכשיו, או משהו אחר ----------
# סימנים לדיווח חי. אם יש אחד מהם, ההודעה נחשבת דיווח גם אם יש בה מילים של סיכום או דעה.
LIVE = re.compile(r"בשעה \d|התקבל דיווח|היכנסו|הכנסו|למרחב המוגן|לפני זמן קצר|לפני דקות|ממש עכשיו|כעת|ברגעים אלו|"
                  r"בשעה זו|בשעה האחרונה|בשעות האחרונות|מבזק|דיווח ראשוני|פועלים במקום|בזירה|בדרך לזירה|"
                  r"לוחמי האש|צוותי כיבוי|חובשים ופראמדיקים|🚨|🔴|במהלך השעות הקרובות|בשעות הקרובות|"
                  r"יכולים לצאת|הוסר החשש|נוטרל|נוטרלו|צפוי להתבצע|צפוי להימשך|צפי התיקון|הצפי לתיקון")
GENRES = [
    # (סוגה, ביטוי). הראשון שמתאים קובע.
    ("opinion", r"לדעתי|לטעמי|בעיניי|אני חושב|אני חושבת|אני סבור|אני סבורה|מאמר|פרשנות|טור דעה|אתחיל ב|"
                r"אסביר|נשאלת השאלה|השאלה הגדולה|הגיע הזמן ש|כולנו יודעים|המונח|האידיוט|התבוסה|הכישלון ה|"
                r"ברשת תוקפים|ציוץ|צייץ|ציייצה|בראיון ל|אמר בראיון|כתב בטור|פודקאסט"),
    ("politics", r"ח[\"״]כ |חבר הכנסת|חברת הכנסת|במליאת הכנסת|ועדת ה|הקואליציה|האופוזיציה|בג[\"״]ץ|הצעת חוק|"
                 r"הממשלה אישרה|ישיבת הממשלה|הקבינט אישר|סקר:|סקר מנדטים"),
    ("followup", r"נעצר|נעצרו|נעצרה|ועצרו|ולעצור|מעצרו|מעצרם|כתב אישום|כתבי אישום|בית המשפט|בית הדין|גזר הדין|"
                 r"נגזרו|הורשע|הורשעה|נידון|נידונה|הסגיר את עצמו|חשוד במעורבות|חשודים במעורבות|"
                 r"בשבוע החולף|בשבוע האחרון|בחודש האחרון|בתקופה האחרונה|במהלך סוף השבוע|בסוף השבוע האחרון|"
                 r"סיכום (?:ה)?(?:שבוע|חודש|שנה|פעילות)|מבצע אכיפה|אכיפה נגד|נתפסו|סיכלו|"
                 r"בהמשך לאירוע|על רקע האירוע|האירוע אתמול|אמש נרצח|לפני (?:שבוע|חודש|שנה|שנתיים|\d+ שנים)|"
                 r"יום השנה|לזכר|אזכרה|הלווית|הובא למנוחות|הובאה למנוחות|נחקר|חקירת המשטרה|התחקיר"),
    ("guidance", r"לרענן|תזכורת|נבקש להזכיר|טיפים|כיצד להתכונן|איך להתכונן|מומלץ להצטייד|הנחיות כלליות"),
]
GENRE_RX = [(g, re.compile(rx)) for g, rx in GENRES]
GENRE_NAMES = {"report": "דיווח", "opinion": "מאמר או דעה", "politics": "פוליטיקה", "followup": "סיכום, מעצר או המשך",
               "guidance": "הנחיות כלליות"}


def genre(text: str) -> str:
    """'report' = ידיעה על אירוע שקורה עכשיו או הודעה רשמית לציבור; אחרת: סוג התוכן."""
    t = re.sub(r"\s+", " ", text or "")
    if LIVE.search(t):
        return "report"
    return next((g for g, rx in GENRE_RX if rx.search(t)), "report")


def analyze(text: str) -> dict:
    t = re.sub(r"\s+", " ", text or "")
    places = find_places(STREET.sub(" ", HOSPITAL.sub(" ", t)))
    if places and ABROAD.search(t) and all(p["name"] in GENERIC for p in places):
        places = []   # למשל "פיצוצים בכפר בלבנון ... ליד גבול הצפון": האירוע בלבנון, לא בצפון
    etype = next((name for name, rx in TYPE_RULES if re.search(rx, t)), None)
    severity = 3 if SEVERE.search(t) else 2 if MEDIUM.search(t) else 1
    names = [p["name"] for p in places]
    g = genre(t)
    regions = regions_for(names)
    return {
        "v": VERSION,
        "north": bool(set(regions) & NORTH_REGIONS),
        "regions": regions,
        "places": names,
        "location": places[0]["name"] if places else None,
        "type": etype,
        "severity": severity,
        "ended": bool(ENDED.search(t)),
        "genre": g,
        # ההחלטה אם להציג: דיווח (לא רעש, לא מאמר/סיכום) + מקום בישראל + סוג אירוע מזוהה
        "relevant": bool(places) and etype is not None and g == "report",
    }


def upgrade(old: dict | None, excerpt: str) -> dict:
    """ניתוח שמור מגרסה קודמת. הודעה שכבר זוהתה כאירוע נותחה מהטקסט המלא, ולכן שומרים
    את המקומות והסוג שלה ורק מוסיפים אזורים. כל השאר מנותח מחדש מהקטע השמור."""
    if old and old.get("v") == VERSION:
        return old
    if old and (old.get("relevant") or old.get("v") == "rules-2"):
        regions = regions_for(old["places"])
        g = genre(excerpt)          # רק הקטע השמור זמין; התחלת ההודעה מספיקה לרוב
        return old | {"v": VERSION, "regions": regions, "north": bool(set(regions) & NORTH_REGIONS), "genre": g,
                      "relevant": bool(old["places"]) and old["type"] is not None and g == "report"}
    return analyze(excerpt)
