def severity_of(etype: str | None, text: str) -> int:
    t = re.sub(r"\s+", " ", text or "")
    if etype == "weather":      # צבע האזהרה של השירות המטאורולוגי
        if re.search(r"אזהרה אדומה|אזהרת אדום", t):
            return 3
        if re.search(r"אזהרה כתומה|אזהרת כתום|סכנת שיטפונות|שיטפון|הצפה", t):
            return 2
        if re.search(r"אזהרה צהובה|אזהרת צהוב", t):
            return 1
    if etype == "cyber":        # התחזות לפיקוד העורף או השבתה של תשתית = קריטי; אזהרת הונאה רגילה = בינוני
        return 3 if re.search(r"פיקוד העורף|תשתית|השבתת|קריסת מערכות|בתי חולים", t) else 2
    m = re.search(r"רעידת אדמה בעוצמה (\d+(?:\.\d)?)", t)
    if m:                       # עוצמה 4 ומעלה = קריטי; מתחת = בינוני
        return 3 if float(m.group(1)) >= 4 else 2
    m = re.search(r"שיבושים בטיסות.*?(\d+) מתוך (\d+) הטיסות[^.]*בוטלו", t)
    if m:                       # חצי מהטיסות ומעלה בוטלו = קריטי
        return 3 if int(m.group(1)) * 2 >= int(m.group(2)) else 2
    if "שיבושים בטיסות" in t:
        return 2
    if CRITICAL.search(t) and not (FALSE_ALARM.search(t) and etype == "security"):
        return 3
    many = bool(MANY.search(t))
    if DEATH.search(t):
        return 3 if many else 2
    if GRAVE.search(t):
        return 3 if many and re.search(r"פצועים קשה|נפצעו קשה|(?:\d|שני|שלושה)\s+פצועים קשה|רב.נפגעים", t) else 2
    if etype == "security":
        if re.search(r"יישמעו|ייתכנו רעשי|ישמעו רעשי|רעשי פיצוצים|תרגיל|ניסוי מתוכנן", t):
            return 1                # הודעה מראש על פעילות מתוכננת
        return 2                    # חפץ חשוד, ירי, התרעת שווא, אירוע אלימות
    if etype in ("closure", "infrastructure", "weather"):
        return 1 if MINOR.search(t) else 2
    if etype == "fire":
        return 2 if BUILDING_FIRE.search(t) and not MINOR.search(t) else 1
    if etype in ("medical", "accident"):
        return 2 if many and not re.search(r"באורח קל|פצועים קל|ללא נפגעים", t) else 1
    return 1


